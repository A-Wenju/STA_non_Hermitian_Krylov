"""
core.py -- all physics for the interacting Hatano-Nelson model (open and
periodic boundaries): model construction, time evolution, exact and
truncated-Krylov counterdiabatic (CD) driving, and the spectral diagnostics
(adiabatic reference, condition-(17) window) used to build the three figures

    HN_OBC_CD_fig            (data_obc_cd.py     -> plot.py obc_cd)
    HN_PBC_Excess_Energy     (data_pbc_excess.py -> plot.py pbc_excess)
    HN_PBC_CD                (data_pbc_cd.py     -> plot.py pbc_cd)

Model (Eq. 55 of the manuscript), fixed particle number N/2:

    H_HN(h) = (J/2) sum_n [ e^{a h} c^dag_n c_{n+1} + e^{-a h} c^dag_{n+1} c_n ]
              + U sum_n n_n n_{n+1}

with either open bonds (n = 0..N-2) or a periodic wrap bond (n = 0..N-1, mod N).

Open boundaries admit an EXACT adiabatic gauge potential for h,

    A_h = -i a X,        X = sum_n n c^dag_n c_n ,

via the imaginary gauge transform S(h) = exp(-a h X); see `evolve_obc_exact`.
Periodic boundaries have no such closed form (S is not single-valued on a
ring), so the CD term there is built from a truncated Krylov subspace
generated by L = [H, .] acting on d_h H (`agp`, `agp_grid`, `evolve_cd`).

All matrices are dense (D = C(N, N/2), N=10 -> D=252), which is what makes
exact diagonalisation per h-point (needed for the Krylov ground-state
projection and the condition-(17) tracked spectrum) affordable.
"""

import numpy as np
import scipy.sparse as sp
from itertools import combinations
from scipy.linalg import expm
from scipy.optimize import linear_sum_assignment

# ----------------------------------------------------------------------
# Basis and model operators
# ----------------------------------------------------------------------

def basis(N, Np):
    """Fixed-filling occupation-number basis as sorted bitmasks."""
    states = sorted(sum(1 << o for o in occ) for occ in combinations(range(N), Np))
    return states, {s: i for i, s in enumerate(states)}


def _hop(m, i, j):
    """<m'| c^dag_i c_j |m>. Returns (new_state, fermionic_sign) or None.

    The "count fermions below the site" convention gives the correct
    Jordan-Wigner sign for the periodic wrap bond as well as open bonds.
    """
    if not (m >> j) & 1:
        return None
    m1 = m ^ (1 << j)
    s = bin(m & ((1 << j) - 1)).count("1")
    if (m1 >> i) & 1:
        return None
    s += bin(m1 & ((1 << i) - 1)).count("1")
    return m1 | (1 << i), (-1) ** s


def model_operators(N, Np, pbc):
    """
    Precompute the h-independent pieces so H(h) is assembled by scalar
    reweighting:

        H(h) = (J/2) [ e^{a h} T_p + e^{-a h} T_m ] + U V

    Returns T_p, T_m (dense complex, D x D), V (diagonal, real), X (diagonal
    position operator, sites labelled 1..N), D.
    """
    states, idx = basis(N, Np)
    D = len(states)
    T_p = np.zeros((D, D), dtype=complex)   # sum_n c^dag_n c_{n+1}
    T_m = np.zeros((D, D), dtype=complex)   # sum_n c^dag_{n+1} c_n
    V = np.zeros(D)                          # nearest-neighbour interaction
    X = np.zeros(D)                          # position operator
    bonds = [(n, (n + 1) % N) for n in range(N if pbc else N - 1)]

    for col, m in enumerate(states):
        X[col] = sum(n + 1 for n in range(N) if (m >> n) & 1)
        for (i, j) in bonds:
            V[col] += ((m >> i) & 1) * ((m >> j) & 1)
            r = _hop(m, i, j)
            if r is not None:
                T_p[idx[r[0]], col] += r[1]
            r = _hop(m, j, i)
            if r is not None:
                T_m[idx[r[0]], col] += r[1]
    return T_p, T_m, V, X, D


def hamiltonian(h, ops, J=1.0, U=1.0, a=1.0):
    T_p, T_m, V, X, D = ops
    return 0.5 * J * (np.exp(a * h) * T_p + np.exp(-a * h) * T_m) \
        + U * np.diag(V).astype(complex)


def dH(h, ops, J=1.0, U=1.0, a=1.0):
    """d H(h) / d h, needed to seed the Krylov AGP at periodic boundaries."""
    T_p, T_m, V, X, D = ops
    return 0.5 * J * a * (np.exp(a * h) * T_p - np.exp(-a * h) * T_m)


# ----------------------------------------------------------------------
# Generic time evolution (exponential-midpoint propagator, Taylor action)
# ----------------------------------------------------------------------

def _taylor_step(gen, psi, dt, order=16):
    """
    psi <- exp(-i dt gen) psi by truncated Taylor series.

    Chosen over scipy.linalg.expm because we only need the action on a
    vector, which costs `order` matrix-vector products instead of a full
    matrix exponential. order=16 is far beyond convergence for ||gen|| dt <~ 0.5.
    """
    term = psi
    out = psi.copy()
    for k in range(1, order + 1):
        term = (-1j * dt / k) * (gen @ term)
        out = out + term
    return out


def evolve(tau, ops, J=1.0, U=1.0, a=1.0, h0=0.1, dt_target=0.02, max_steps=8000):
    """
    Linear ramp h(t) = h0 t/tau, no CD term, exponential-midpoint propagator.

    The state is renormalised after every step. This is essential at PBC,
    where the norm grows like exp(int Im E dt) and would overflow; it does
    not affect <H>/<psi|psi>, which is all the excess energy needs.
    """
    n_steps = int(np.clip(np.ceil(tau / dt_target), 200, max_steps))
    dt = tau / n_steps
    H0 = hamiltonian(0.0, ops, J, U, a)
    psi = np.linalg.eigh(H0.real)[1][:, 0].astype(complex)
    for k in range(n_steps):
        gen = hamiltonian(h0 * (k + 0.5) / n_steps, ops, J, U, a)
        psi = _taylor_step(gen, psi, dt)
        psi /= np.linalg.norm(psi)
    return psi


# ----------------------------------------------------------------------
# Open boundaries: exact CD term A_h = -i a X
# ----------------------------------------------------------------------

def evolve_obc_exact(tau, ops, use_cd, J=1.0, U=1.0, a=1.0, h0=0.1):
    """
    Exact closed-form propagator for OPEN boundaries and a LINEAR ramp. No
    time stepping. Valid for the bare ramp (use_cd=False) and for the exact
    CD drive (use_cd=True); see the module docstring for A_h.

    Substituting psi = S(h(t)) phi with S = exp(-a h X) into
    i d_t psi = H(h(t)) psi and using d_t S = -a hdot X S, S^{-1} X S = X:

        i d_t phi = ( H(0) + i a hdot X ) phi          (no CD)
        i d_t phi = H(0) phi                           (with CD, the two X
                                                          terms cancel)

    For a linear ramp hdot = h0/tau is constant, so both generators are
    time-independent and the evolution is a single matrix exponential. With
    CD this gives psi(tau) = S(h0) psi_0 e^{-i E_0 tau}, i.e. exactly the
    instantaneous ground state, so the excess energy is zero for every tau.
    """
    T_p, T_m, V, X, D = ops
    H0 = hamiltonian(0.0, ops, J, U, a)
    phi0 = np.linalg.eigh(H0.real)[1][:, 0].astype(complex)
    hdot = h0 / tau
    gen = H0 if use_cd else H0 + 1j * a * hdot * np.diag(X).astype(complex)
    phi = expm(-1j * tau * gen) @ phi0
    return np.exp(-a * h0 * X) * phi          # multiply by S(h0), diagonal


def evolve_obc_stepper(tau, ops, use_cd, J=1.0, U=1.0, a=1.0, h0=0.1,
                       dt_target=0.02):
    """
    General (any ramp, any CD term) time stepper for open boundaries, used
    only to cross-check `evolve_obc_exact` for the linear ramp -- see
    `verify_obc` in data_obc_cd.py. use_cd=True adds the exact generator
    hdot * A_h = -i a hdot X.
    """
    T_p, T_m, V, X, D = ops
    n_steps = max(200, int(np.ceil(tau / dt_target)))
    dt = tau / n_steps
    hdot = h0 / tau
    CD = -1j * a * hdot * np.diag(X).astype(complex) if use_cd else 0.0

    H0 = hamiltonian(0.0, ops, J, U, a)
    psi = np.linalg.eigh(H0.real)[1][:, 0].astype(complex)
    for k in range(n_steps):
        h_mid = h0 * (k + 0.5) / n_steps
        gen = hamiltonian(h_mid, ops, J, U, a)
        if use_cd:
            gen = gen + CD
        psi = _taylor_step(gen, psi, dt)
    return psi


